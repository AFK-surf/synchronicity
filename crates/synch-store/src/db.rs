/// Whether this thread is inside a [`Store::transaction`] scope.
///
/// [`Store::transaction`] holds the connection `MutexGuard` for the whole of
/// its closure and `std::sync::Mutex` is not reentrant, so any `Store` method
/// called from inside that closure blocks the thread against a lock it is
/// itself holding. Nothing prevented it: the `Store` handle is in scope at
/// every call site (`self.store.transaction(|txn| …)`), `Txn` deliberately
/// exposes a narrower surface than `Store` — no `blob`, no `pinned_blobs`, no
/// `prune_history_before` — so reaching for the wrong one is easy, and the
/// compiler has nothing to say about it.
///
/// What makes that worth ten lines of guard is the failure mode. A deadlock is
/// not a panic: the thread simply stops, so a test that exercised the path
/// would hang until the harness timed out rather than fail with a location.
/// This turns it into a named assertion, in debug and test builds only.
#[cfg(debug_assertions)]
mod reentry {
    use std::cell::Cell;

    thread_local! {
        static DEPTH: Cell<usize> = const { Cell::new(0) };
    }

    /// Marks the calling thread as inside a transaction until it is dropped.
    pub(super) struct Scope;

    impl Scope {
        pub(super) fn enter() -> Scope {
            DEPTH.with(|d| d.set(d.get() + 1));
            Scope
        }
    }

    impl Drop for Scope {
        fn drop(&mut self) {
            DEPTH.with(|d| d.set(d.get().saturating_sub(1)));
        }
    }

    pub(super) fn active() -> bool {
        DEPTH.with(|d| d.get()) > 0
    }
}

#[cfg(not(debug_assertions))]
mod reentry {
    pub(super) struct Scope;

    impl Scope {
        pub(super) fn enter() -> Scope {
            Scope
        }
    }

    pub(super) fn active() -> bool {
        false
    }
}

/// Whether this thread is inside a transaction scope.
fn in_transaction() -> bool {
    reentry::active()
}

/// The node's metadata store.
///
/// All writes funnel through one mutex-guarded connection, which is how the
/// §10 "single writer task" discipline is realized here: every multi-step state
/// change (head flips, publish batches) runs inside one SQLite transaction on
/// that connection, so no partial state is ever observable.
#[derive(Debug)]
pub struct Store {
    conn: Mutex<Connection>,
    data_dir: PathBuf,
    /// Whether complete out-of-line bytes are only cache until explicitly
    /// finalized into a remote backend.
    remote_cas: std::sync::atomic::AtomicBool,
    /// Roots a full walk has established this store holds entirely.
    ///
    /// "Do I hold this whole trie?" is asked on every `Hello` (§5.1) and
    /// answered by walking everything reachable — so without this a converged
    /// cluster pays for the size of its metadata on every anti-entropy round,
    /// on both sides, forever. A content-addressed root that was complete
    /// stays complete, so the walk is owed once per root and not once per
    /// exchange. Process-local and rebuilt on demand: losing it costs one
    /// walk, never correctness.
    complete_roots: Mutex<std::collections::HashSet<Hash>>,
    /// Objects a CAS write is currently between its first byte and its commit.
    ///
    /// The collector and the writers agree about *rows* through SQLite and did
    /// not originally agree about *bytes*.
    /// `write_slice` and `write_proof` do all their file IO with no lock held
    /// (creating, growing, decoding, two fsyncs and two parent fsyncs) and only
    /// then take the connection to commit the bitmap. So a sweep could decide an
    /// object was collectable, delete its row, unlink its files, and have the
    /// writer's commit land *after* the unlinks — leaving a row that claims
    /// verified groups with no payload behind them. That state advertises the
    /// object to the whole membership through `local_ad`, fails every read, and
    /// self-heals never: `gc_content` skips it because an entry names it,
    /// `gc_orphans` skips it because it *has* a row, and `write_slice`
    /// early-returns when the row says complete.
    ///
    /// `delete_blob_if_collectable` held its guard across the unlinks to close
    /// exactly this window and could not: holding it only forces the writer's
    /// commit to land later, which is the wrong side. What was missing is a fact
    /// the collector could read — "somebody is writing this object" — so here it
    /// is. Held for the whole write and consulted by every sweep while it holds
    /// the shared order guard. The registry is process-wide per canonical
    /// datadir, so independently opened Store values see the same fact; the
    /// lifecycle lock excludes a second process.
    cas_coord: Arc<CasCoord>,
    /// A latch this crate's own tests use to stop a CAS write between its
    /// bytes and its row — the window `writing` exists for. Absent from every
    /// other build.
    #[cfg(test)]
    write_window: Mutex<Option<std::sync::Arc<WriteWindow>>>,
}

/// Process-wide CAS ordering shared by every `Store` opened on one datadir.
///
/// The lifecycle lock excludes other processes. This registry closes the
/// smaller same-process hole: two independently opened Store values must still
/// agree about writers and serialize lease registration against unlink.
#[derive(Debug, Default)]
struct CasCoord {
    order: Mutex<()>,
    writing: Mutex<HashMap<Hash, usize>>,
}

fn cas_coord_for(data_dir: &Path) -> Arc<CasCoord> {
    static COORDS: OnceLock<Mutex<HashMap<PathBuf, Weak<CasCoord>>>> = OnceLock::new();
    let key = std::fs::canonicalize(data_dir).unwrap_or_else(|_| data_dir.to_path_buf());
    let mut coords = COORDS
        .get_or_init(|| Mutex::new(HashMap::new()))
        .lock()
        .unwrap_or_else(PoisonError::into_inner);
    if let Some(coord) = coords.get(&key).and_then(Weak::upgrade) {
        return coord;
    }
    let coord = Arc::new(CasCoord::default());
    coords.insert(key, Arc::downgrade(&coord));
    coord
}

/// A pause a test can install inside a CAS write, at the instant the payload is
/// on disk and no row yet claims it.
///
/// The window `writing` exists to protect is real but short — a rename, an
/// fsync and a row — and on a platform whose `fsync` returns before the disk
/// does it is about a millisecond. A collector thread spinning to catch it
/// therefore catches it on most machines and not on a loaded one, which is how
/// `an_ingest_that_recreates_a_collectable_object_keeps_its_bytes` came to fail
/// on a macOS runner while passing everywhere else. Holding the window open
/// from inside the writer makes the collector's observation a fact rather than
/// a race, and leaves the property under test unchanged.
#[cfg(test)]
#[derive(Debug, Default)]
pub(crate) struct WriteWindow {
    /// `(the writer is inside the window, the observer is done with it)`.
    state: Mutex<(bool, bool)>,
    changed: std::sync::Condvar,
}

#[cfg(test)]
impl WriteWindow {
    /// Called by the writer: announces the window and blocks until released.
    fn hold(&self) {
        let mut state = self.state.lock().unwrap_or_else(PoisonError::into_inner);
        state.0 = true;
        self.changed.notify_all();
        while !state.1 {
            state = self
                .changed
                .wait(state)
                .unwrap_or_else(PoisonError::into_inner);
        }
    }

    /// Called by the observer: blocks until a writer is inside the window.
    pub(crate) fn wait_entered(&self) {
        let mut state = self.state.lock().unwrap_or_else(PoisonError::into_inner);
        while !state.0 {
            state = self
                .changed
                .wait(state)
                .unwrap_or_else(PoisonError::into_inner);
        }
    }

    /// Called by the observer: lets the writer out of the window.
    pub(crate) fn release(&self) {
        let mut state = self.state.lock().unwrap_or_else(PoisonError::into_inner);
        state.1 = true;
        self.changed.notify_all();
    }
}

/// Marks an object as being written, until dropped.
///
/// A count rather than a flag: two fetches of one root — replica acquisition and a
/// `synch cat`, say — overlap legitimately, and the first to finish must not
/// clear the mark the second is relying on.
#[derive(Debug)]
pub(crate) struct WriteLease<'a> {
    store: &'a Store,
    root: Hash,
}

impl Drop for WriteLease<'_> {
    fn drop(&mut self) {
        // LEAN-MODEL: cas-write-lease-end (Cas.WriteAbort)
        // `Cas.WriteAbort` also covers the successful lease end: the
        // protection disappears only after the writer has stopped touching bytes.
        let mut writing = self.store.writing();
        if let Some(count) = writing.get_mut(&self.root) {
            *count -= 1;
            if *count == 0 {
                writing.remove(&self.root);
            }
        }
    }
}

/// How many roots the completeness memo holds before it is dropped wholesale.
///
/// One entry per root this node has confirmed, which is one per published head
/// and one per peer head adopted; a long-lived node would otherwise accumulate
/// them without bound. Dropping the lot costs a walk on the roots still in use
/// and nothing else, which is why there is no LRU here.
const COMPLETE_ROOTS_MAX: usize = 4096;

/// Who is responsible for moving WAL frames back into the database file.
///
/// The store has always assumed a replicating checkpointer might be running
/// beside it — its 30-second `busy_timeout` exists for exactly that — but that
/// checkpointer was assumed to be *another process* (Litestream), which SQLite
/// coordinates with through the WAL index whether or not anyone declares it.
/// A replicator inside this process needs the opposite: a promise that nothing
/// else checkpoints, so it can ship frames before they are recycled.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Checkpointing {
    /// SQLite's own autocheckpoint, and any external process that runs one.
    #[default]
    Automatic,
    /// The embedder's, exclusively: SQLite's autocheckpoint is disabled and
    /// the embedder is expected to run its own on its own schedule.
    ///
    /// A WAL that nobody checkpoints grows without bound, so taking this on
    /// means owning it — see `docs/CLOUD-DATAPLANE.md` §5.3, where shipping a
    /// frame *before* it can be recycled is what makes the replica stream
    /// complete.
    Embedder,
}

/// Knobs that must be settled before the first statement runs.
#[derive(Debug, Clone, Copy, Default)]
pub struct StoreOptions {
    /// Who checkpoints the WAL.
    pub checkpointing: Checkpointing,
}

impl Store {
    /// Opens (creating if needed) the store rooted at `data_dir`.
    pub fn open(data_dir: impl AsRef<Path>) -> Result<Store> {
        Store::open_with(data_dir, StoreOptions::default())
    }

    /// Opens the store with non-default [`StoreOptions`].
    pub fn open_with(data_dir: impl AsRef<Path>, options: StoreOptions) -> Result<Store> {
        let data_dir = data_dir.as_ref().to_path_buf();
        std::fs::create_dir_all(&data_dir)?;
        std::fs::create_dir_all(data_dir.join(CAS_DIR))?;
        // The DB holds this node's device secret key and the S3 access keys, so
        // it must not be world-readable (§3). `synch init` hardens the datadir,
        // but the daemon can be pointed at a fresh dir (or a restored backup)
        // without it — so the store defends its own files unconditionally.
        harden_permissions(&data_dir);
        let conn = Connection::open(data_dir.join(DB_FILE))?;
        let cas_coord = cas_coord_for(&data_dir);
        let store = Store {
            conn: Mutex::new(conn),
            data_dir,
            remote_cas: std::sync::atomic::AtomicBool::new(false),
            complete_roots: Mutex::new(std::collections::HashSet::new()),
            cas_coord,
            #[cfg(test)]
            write_window: Mutex::new(None),
        };
        store.init(options)?;
        // WAL/SHM sidecars are created by `init` (WAL mode); tighten them too.
        harden_db_files(&store.data_dir);
        Ok(store)
    }

    fn init(&self, options: StoreOptions) -> Result<()> {
        let mut conn = self.conn();
        conn.pragma_update(None, "foreign_keys", "ON")?;
        // WAL keeps readers off the writer's back; NORMAL is the §10 setting.
        let _: String = conn.query_row("PRAGMA journal_mode=WAL", [], |row| row.get(0))?;
        conn.pragma_update(None, "synchronous", "NORMAL")?;
        if options.checkpointing == Checkpointing::Embedder {
            // Zero disables it. Set before `migrate` runs, so not one frame of
            // this store's life is recycled by anybody but the embedder.
            conn.pragma_update(None, "wal_autocheckpoint", 0)?;
        }
        // Litestream checkpoints in a second process. A trie GC transaction
        // can legitimately hold the write lock beyond SQLite's old five
        // second wait, so give replication and daemon writers room to queue
        // instead of surfacing transient SQLITE_BUSY as an engine fault.
        conn.pragma_update(None, "busy_timeout", 30_000)?;
        migrate(&mut conn, MIGRATIONS)?;
        Ok(())
    }

    /// The data directory.
    pub fn data_dir(&self) -> &Path {
        &self.data_dir
    }

    /// The database file.
    pub fn db_path(&self) -> PathBuf {
        self.data_dir.join(DB_FILE)
    }

    /// Selects remote durability semantics for this process.
    ///
    /// Must be called during node open, before any CAS writer runs. Every
    /// complete write, inline or out-of-line, remains staged until the remote
    /// backend explicitly marks it durable.
    pub fn set_remote_cas(&self, remote: bool) {
        self.remote_cas
            .store(remote, std::sync::atomic::Ordering::Release);
    }

    pub(crate) fn complete_is_durable(&self) -> bool {
        !self.remote_cas.load(std::sync::atomic::Ordering::Acquire)
    }

    /// The CAS root directory.
    pub(crate) fn cas_dir(&self) -> PathBuf {
        self.data_dir.join(CAS_DIR)
    }

    /// The directory ingests stream into before renaming onto a content
    /// address (§7.1).
    pub fn staging_dir(&self) -> PathBuf {
        self.cas_dir().join(STAGING_DIR)
    }

    pub(crate) fn conn(&self) -> MutexGuard<'_, Connection> {
        debug_assert!(
            !in_transaction(),
            "Store::conn() was called from inside a transaction. The connection \
             mutex is not reentrant, so this deadlocks: use the `Txn` the closure \
             was handed, not the `Store` it came from."
        );
        // The other half of the same idea (§10). Every acquisition here is a
        // wait on the one global connection mutex, and a long holder — a publish
        // batch, a GC pass, a slice commit — parks whoever is waiting for as
        // long as it runs. On a runtime worker that is the endpoint, the control
        // socket and every timer in the process, so blocking work goes to the
        // blocking pool and the invariant is checked here.
        synch_core::assert_off_runtime("a Store connection acquisition");
        self.conn.lock().unwrap_or_else(PoisonError::into_inner)
    }

    /// Runs `f` against the raw transaction handle, committing on `Ok`.
    ///
    /// The store's own multi-statement writes use this; callers outside the
    /// crate get [`Store::transaction`], which hands out a [`Txn`] scope rather
    /// than a `rusqlite` type.
    pub(crate) fn with_tx<T>(
        &self,
        f: impl FnOnce(&rusqlite::Transaction<'_>) -> Result<T>,
    ) -> Result<T> {
        let conn = self.conn();
        let _scope = reentry::Scope::enter();
        let tx = conn.unchecked_transaction()?;
        let out = f(&tx)?;
        tx.commit()?;
        Ok(out)
    }

    /// Runs `f` in a transaction that takes SQLite's write lock up front.
    ///
    /// [`Store::with_tx`] begins deferred, which acquires the read lock first
    /// and upgrades it on the first write. That is right for a transaction that
    /// only writes, and wrong for one that *reads and then writes what it read*:
    /// under multi-process WAL, another process committing in between makes the
    /// upgrade fail with `SQLITE_BUSY_SNAPSHOT` rather than wait, because the
    /// snapshot the read saw is no longer the tip. Nothing is corrupted, but the
    /// work the transaction was about to record is lost and the caller has to
    /// find out and repeat it.
    ///
    /// `BEGIN IMMEDIATE` takes the write lock at the start instead, so the
    /// contention is handled by `busy_timeout` like any other — a wait rather
    /// than a failure. The read-union-write bitmap commit
    /// ([`Store::commit_groups`](crate::Store)) is the path that needs it.
    pub(crate) fn with_immediate_tx<T>(
        &self,
        f: impl FnOnce(&rusqlite::Transaction<'_>) -> Result<T>,
    ) -> Result<T> {
        let mut conn = self.conn();
        let _scope = reentry::Scope::enter();
        let tx = conn.transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)?;
        let out = f(&tx)?;
        tx.commit()?;
        Ok(out)
    }

    /// Runs `f` inside a single SQLite transaction, committing on `Ok` and
    /// rolling the whole thing back on `Err`.
    ///
    /// This is the unit of atomicity §10 asks for: "every multi-step state
    /// change (head flips, publish batches) is a single transaction and no
    /// partial state is ever observable". The scope handed to `f` is a [`Txn`],
    /// which is both a [`NodeStore`] — so trie writes join the transaction —
    /// and the head, history, and materialization surface a publish or a
    /// promotion needs. No `rusqlite` type crosses the boundary.
    ///
    /// The error type is the caller's, so an engine or a net operation can run
    /// its own failures through the same rollback: anything that converts from
    /// [`StoreError`] works.
    ///
    /// The transaction begins **immediate**. Every caller here reads and then
    /// writes what it read — a publish reads the head it is about to displace,
    /// a promotion reads the pending slot, GC reads the roots it marks from —
    /// which is the one shape `BEGIN DEFERRED` handles badly: it takes the read
    /// lock first and upgrades on the first write, and under multi-process WAL
    /// another process committing in between fails the upgrade outright with
    /// `SQLITE_BUSY_SNAPSHOT` rather than waiting, because the snapshot the read
    /// saw is no longer the tip. Nothing is corrupted, but the work is lost and
    /// the caller has to notice. Taking the write lock up front turns that into
    /// an ordinary `busy_timeout` wait. In-process the connection mutex already
    /// serializes writers, so this costs nothing there.
    pub fn transaction<T, E>(
        &self,
        f: impl FnOnce(&Txn<'_>) -> std::result::Result<T, E>,
    ) -> std::result::Result<T, E>
    where
        E: From<StoreError>,
    {
        let mut conn = self.conn();
        let _scope = reentry::Scope::enter();
        let tx = conn
            .transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
            .map_err(StoreError::from)?;
        // On `Err` the `Transaction` is dropped without a commit, which is a
        // rollback: nothing the closure wrote is observable afterwards.
        let out = f(&Txn {
            tx: &tx,
            store: self,
        })?;
        tx.commit().map_err(StoreError::from)?;
        Ok(out)
    }

    // ---- config -----------------------------------------------------------

    /// Reads a config value.
    pub fn config(&self, key: &str) -> Result<Option<String>> {
        Ok(self
            .conn()
            .query_row(
                "SELECT value FROM config WHERE key = ?1",
                params![key],
                |r| r.get(0),
            )
            .optional()?)
    }

    /// Writes a config value.
    pub fn set_config(&self, key: &str, value: &str) -> Result<()> {
        set_config_in(&self.conn(), key, value)
    }

    /// Appends one newline-separated record to a config value, creating the
    /// value if it does not exist yet.
    ///
    /// A config row that holds a *list* — the S3 gateway's bucket map and its
    /// access keys (§9.4) — is read and written by more than one process, and
    /// a read-modify-write of the whole list silently drops whichever concurrent
    /// edit commits first. One SQL statement cannot: the append happens inside
    /// the database, under the same single connection every other write goes
    /// through, so two appends interleave instead of overwriting each other.
    pub fn append_config(&self, key: &str, record: &str) -> Result<()> {
        self.conn().execute(
            "INSERT INTO config (key, value) VALUES (?1, ?2)
             ON CONFLICT(key) DO UPDATE SET value = value || char(10) || excluded.value",
            params![key, record],
        )?;
        Ok(())
    }

    /// Deletes a config value.
    pub fn clear_config(&self, key: &str) -> Result<()> {
        clear_config_in(&self.conn(), key)
    }

    /// This node's own [`OriginId`], if `synch init` has run.
    pub fn self_origin(&self) -> Result<Option<OriginId>> {
        match self.config("self_origin_id")? {
            None => Ok(None),
            Some(text) => OriginId::from_str(&text)
                .map(Some)
                .map_err(|e| StoreError::column("config.self_origin_id", e.to_string())),
        }
    }

    /// Sets this node's own [`OriginId`].
    pub fn set_self_origin(&self, origin: &OriginId) -> Result<()> {
        self.set_config("self_origin_id", &origin.canonical())
    }

    /// The membership domain this node belongs to, if it has one (§3.1).
    ///
    /// Held separately from `self_origin_id` even though it is that origin's
    /// `@domain` half, because it has to be readable *before* there is a name
    /// to read it out of: a node that has never identified has only this.
    pub fn membership_domain(&self) -> Result<Option<String>> {
        self.config(DOMAIN_KEY)
    }

    /// Sets the membership domain, or clears it when given `None`.
    pub fn set_membership_domain(&self, domain: Option<&str>) -> Result<()> {
        match domain {
            Some(domain) => self.set_config(DOMAIN_KEY, domain),
            None => self.clear_config(DOMAIN_KEY),
        }
    }

    /// Whether this node expects its zone to name it (§3.1).
    ///
    /// `false` for a delegate, which belongs to a cluster and takes its name
    /// from no zone in it (§3.5). This cannot be inferred: on a first start,
    /// "the zone answered and does not name me" and "my record has not
    /// propagated yet" are the same answer, and guessing wrong either refuses
    /// to start a delegate or lets a member silently publish under a key origin
    /// it will have to migrate away from. So the operator says which, once.
    pub fn membership_expects_name(&self) -> Result<bool> {
        Ok(self.config(UNNAMED_KEY)?.as_deref() != Some("1"))
    }

    /// Records whether the zone is expected to name this node.
    pub fn set_membership_expects_name(&self, expects: bool) -> Result<()> {
        match expects {
            true => self.clear_config(UNNAMED_KEY),
            false => self.set_config(UNNAMED_KEY, "1"),
        }
    }

    /// Every identity this node has adopted from its zone, oldest first (§3.1).
    pub fn identity_history(&self) -> Result<Vec<IdentityAdoption>> {
        let conn = self.conn();
        let mut stmt = conn.prepare(
            "SELECT at, previous, adopted, node_id, domain FROM identity_history ORDER BY at",
        )?;
        let rows = stmt.query_map([], |row| {
            Ok((
                row.get::<_, i64>(0)?,
                row.get::<_, Option<String>>(1)?,
                row.get::<_, String>(2)?,
                row.get::<_, Vec<u8>>(3)?,
                row.get::<_, String>(4)?,
            ))
        })?;
        let mut out = Vec::new();
        for row in rows {
            let (at, previous, adopted, node_id, domain) = row?;
            out.push(IdentityAdoption {
                at,
                previous: previous
                    .map(|text| origin_column(text, "identity_history.previous"))
                    .transpose()?,
                adopted: origin_column(adopted, "identity_history.adopted")?,
                node_id: key_column(node_id, "identity_history.node_id")?,
                domain,
            });
        }
        Ok(out)
    }

    // ---- device keys ------------------------------------------------------

    /// Stores a device key.
    pub fn add_device_key(&self, secret: &SecretKey, state: KeyState, now: i64) -> Result<()> {
        self.conn().execute(
            "INSERT INTO device_keys (node_id, secret_key, state, created_at) VALUES (?1, ?2, ?3, ?4)
             ON CONFLICT(node_id) DO UPDATE SET state = excluded.state",
            params![
                secret.public().as_bytes().to_vec(),
                secret.to_bytes().to_vec(),
                state.as_str(),
                now
            ],
        )?;
        Ok(())
    }

    /// Every locally held device key, active ones first.
    pub fn device_keys(&self) -> Result<Vec<DeviceKey>> {
        let conn = self.conn();
        let mut stmt = conn.prepare(
            "SELECT node_id, secret_key, state, created_at FROM device_keys
             ORDER BY state = 'active' DESC, created_at DESC",
        )?;
        let rows = stmt.query_map([], |row| {
            Ok((
                row.get::<_, Vec<u8>>(0)?,
                row.get::<_, Vec<u8>>(1)?,
                row.get::<_, String>(2)?,
                row.get::<_, i64>(3)?,
            ))
        })?;
        let mut out = Vec::new();
        for row in rows {
            let (node_id, secret, state, created_at) = row?;
            let node_id: [u8; 32] = node_id
                .try_into()
                .map_err(|_| StoreError::column("device_keys.node_id", "not 32 bytes"))?;
            let secret: [u8; 32] = secret
                .try_into()
                .map_err(|_| StoreError::column("device_keys.secret_key", "not 32 bytes"))?;
            out.push(DeviceKey {
                node_id: NodeId::from_bytes(&node_id)
                    .map_err(|e| StoreError::column("device_keys.node_id", e.to_string()))?,
                secret: SecretKey::from_bytes(&secret),
                state: KeyState::parse(&state)?,
                created_at,
            });
        }
        Ok(out)
    }

    /// The key currently used for signing (§3.4: exactly one at any moment).
    pub fn active_device_key(&self) -> Result<Option<DeviceKey>> {
        Ok(self
            .device_keys()?
            .into_iter()
            .find(|k| k.state == KeyState::Active))
    }

    /// Marks a device key as retiring or active.
    pub fn set_device_key_state(&self, node_id: &NodeId, state: KeyState) -> Result<()> {
        set_device_key_state_in(&self.conn(), node_id, state)
    }

    /// Deletes a retired device key's secret (§3.4 step 4).
    pub fn remove_device_key(&self, node_id: &NodeId) -> Result<()> {
        self.conn().execute(
            "DELETE FROM device_keys WHERE node_id = ?1",
            params![node_id.as_bytes().to_vec()],
        )?;
        Ok(())
    }
}

/// One SQLite transaction, as the rest of the workspace sees it.
///
/// Everything a publish or a head flip touches — trie nodes and values, the
/// two head slots, `head_history`, and the materialized `entries` /
/// `blob_providers` views — is reachable from here and lands in the same
/// commit. Obtained only from [`Store::transaction`], which is what makes "one
/// transaction" a property of the type rather than a convention.
#[derive(Debug)]
pub struct Txn<'a> {
    tx: &'a rusqlite::Transaction<'a>,
    store: &'a Store,
}

impl Txn<'_> {
    /// The underlying connection, for the store's own statement helpers.
    pub(crate) fn conn(&self) -> &Connection {
        self.tx
    }

    /// Sets this node's own [`OriginId`], inside the transaction.
    pub fn set_self_origin(&self, origin: &OriginId) -> Result<()> {
        self.set_config("self_origin_id", &origin.canonical())
    }

    /// Marks a device key as retiring or active, inside the transaction.
    ///
    /// A rotation moves two keys' states and must move both or neither: §3.4
    /// says exactly one key is active at any moment, and nothing in the schema
    /// enforces it. As two autocommit statements, a crash or a `BUSY` between
    /// them left the retiring key retired and the incoming key still staged —
    /// zero active keys, so [`Store::active_device_key`] answers `None` and the
    /// daemon refuses to open, which is also the only way to run the command
    /// that would repair it.
    pub fn set_device_key_state(&self, node_id: &NodeId, state: KeyState) -> Result<()> {
        set_device_key_state_in(self.conn(), node_id, state)
    }

    /// Writes a config value, inside the transaction.
    pub fn set_config(&self, key: &str, value: &str) -> Result<()> {
        set_config_in(self.conn(), key, value)
    }

    /// Deletes a config value, inside the transaction.
    pub fn clear_config(&self, key: &str) -> Result<()> {
        clear_config_in(self.conn(), key)
    }

    /// Forgets every redaction boundary, inside the transaction.
    ///
    /// A boundary is a fact about a scope, not about a node, so the memo is
    /// dropped whenever the scope moves — see [`Store::set_read_scope`],
    /// which is the only thing that should call this.
    pub(crate) fn clear_redacted(&self) -> Result<()> {
        self.conn().execute("DELETE FROM redacted_nodes", [])?;
        Ok(())
    }

    /// Sets or clears the membership domain, inside the transaction.
    pub fn set_membership_domain(&self, domain: Option<&str>) -> Result<()> {
        match domain {
            Some(domain) => self.set_config(DOMAIN_KEY, domain),
            None => self.clear_config(DOMAIN_KEY),
        }
    }

    /// Drops the publishing floor, inside the transaction.
    ///
    /// A floor is a promise about seqs under one name (§3.4); carried across an
    /// identity migration it would floor history nobody holds under the name
    /// being adopted.
    pub fn clear_publish_floor(&self) -> Result<()> {
        self.clear_config("publish_floor")
    }

    /// Records an identity adoption, inside the transaction (§3.1).
    ///
    /// `previous` is `None` for a node's first name, which is an adoption like
    /// any other: the zone named a key that had no name, and the trail has to
    /// say when that happened as much as it says when a name was replaced.
    pub fn record_identity_adoption(
        &self,
        previous: Option<&OriginId>,
        adopted: &OriginId,
        node_id: &NodeId,
        domain: &str,
        at: i64,
    ) -> Result<()> {
        self.conn().execute(
            "INSERT INTO identity_history (at, previous, adopted, node_id, domain)
             VALUES (?1, ?2, ?3, ?4, ?5)",
            params![
                at,
                previous.map(|origin| origin.canonical()),
                adopted.canonical(),
                node_id.as_bytes().as_slice(),
                domain,
            ],
        )?;
        Ok(())
    }

    /// Drops every dns binding that did not come from `domain`, inside the
    /// transaction.
    ///
    /// A node resolves the zone that names it and no other (§3.1), so on
    /// adopting a name the bindings vouched for by the zone being left have no
    /// authority behind them any more — and nothing else would remove them
    /// before their own expiry.
    pub fn delete_dns_bindings_other_than(&self, domain: &str) -> Result<usize> {
        Ok(self.conn().execute(
            "DELETE FROM bindings WHERE source = 'dns' AND domain <> ?1",
            params![domain],
        )?)
    }

    /// Drops every delegation an origin issued, inside the transaction.
    ///
    /// Revocation is deletion (§3.5), and these rows are a materialized view
    /// of `d:` leaves in that origin's trie. When the origin itself goes —
    /// which is what adopting a new name does to the old one — the trie those
    /// rows derive from goes with it, and nothing would ever come along to
    /// remove them: materialization only applies deltas, and a vanished origin
    /// publishes no more of them.
    ///
    /// Returns the subjects whose trust this withdrew, so the caller can say
    /// so rather than leave an operator to discover it.
    pub fn delete_delegations_by(&self, issuer: &OriginId) -> Result<Vec<NodeId>> {
        let subjects: Vec<NodeId> = {
            let mut stmt = self.conn().prepare(
                "SELECT node_id FROM bindings WHERE source = 'delegated' AND issuer = ?1",
            )?;
            let rows =
                stmt.query_map(params![issuer.canonical()], |row| row.get::<_, Vec<u8>>(0))?;
            let mut out = Vec::new();
            for row in rows {
                out.push(key_column(row?, "bindings.node_id")?);
            }
            out
        };
        self.conn().execute(
            "DELETE FROM bindings WHERE source = 'delegated' AND issuer = ?1",
            params![issuer.canonical()],
        )?;
        Ok(subjects)
    }

    /// Forgets what peers advertised for an origin, inside the transaction.
    pub fn clear_observed_head(&self, origin: &OriginId) -> Result<()> {
        self.conn().execute(
            "DELETE FROM observed_heads WHERE origin_id = ?1",
            params![origin.canonical()],
        )?;
        Ok(())
    }
}

