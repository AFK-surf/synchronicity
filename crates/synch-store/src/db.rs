/// Directory under the data dir holding blob payloads and outboards (§6.2).
pub const CAS_DIR: &str = "store";
/// Directory under the CAS root holding half-written ingests (§7.1).
///
/// Its own directory, not the CAS root beside the shards. A staging file in the
/// root is a *regular file* where the orphan sweep expects a shard directory,
/// which makes `read_dir` on it fail with `NotADirectory` and would kill the
/// sweep permanently — and only that sweep can remove the file. Under a name of
/// its own the sweep has one rule about one place, and the CAS root holds
/// nothing but directories by construction.
pub(crate) const STAGING_DIR: &str = "incoming";
/// The database file name (§10).
pub const DB_FILE: &str = "synchronicity.db";

/// Restricts the data directory to owner-only access (§3). No-op off Unix.
fn harden_permissions(data_dir: &Path) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(data_dir, std::fs::Permissions::from_mode(0o700));
    }
    #[cfg(not(unix))]
    let _ = data_dir;
}

/// Restricts the database and its WAL/SHM sidecars to owner-only. No-op off
/// Unix. Called after `init`, once WAL mode has created the sidecars.
fn harden_db_files(data_dir: &Path) {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        for name in [DB_FILE, "synchronicity.db-wal", "synchronicity.db-shm"] {
            let path = data_dir.join(name);
            if path.exists() {
                let _ = std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o600));
            }
        }
    }
    #[cfg(not(unix))]
    let _ = data_dir;
}

/// The state of a locally held device key.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyState {
    /// Generated by `key rotate` and waiting for `key activate` (§3.4).
    ///
    /// Its own state, because both neighbors mislead: this key is not signing
    /// anything yet, and calling it "retiring" would tell the operator that the
    /// key they just minted is on its way out.
    Staged,
    /// The key currently used for signing and for the primary endpoint.
    Active,
    /// A key kept alive through a rotation window (§3.4).
    Retiring,
}

impl KeyState {
    /// The `state` column value.
    pub fn as_str(self) -> &'static str {
        match self {
            KeyState::Staged => "staged",
            KeyState::Active => "active",
            KeyState::Retiring => "retiring",
        }
    }

    /// Parses the `state` column value.
    pub fn parse(s: &str) -> Result<Self> {
        match s {
            "staged" => Ok(KeyState::Staged),
            "active" => Ok(KeyState::Active),
            "retiring" => Ok(KeyState::Retiring),
            other => Err(StoreError::column("device_keys.state", other)),
        }
    }
}

