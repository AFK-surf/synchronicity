/// A refusal is keyed by `(hash, path)`; `None` asks whether the node was
/// refused at any position, which is what a walk over what this node *holds*
/// wants to know about a node that is missing.
fn is_redacted_in(conn: &Connection, hash: &Hash, path: Option<&[u8]>) -> Result<bool> {
    Ok(conn
        .query_row(
            "SELECT 1 FROM redacted_nodes WHERE hash = ?1 AND (?2 IS NULL OR path = ?2)",
            params![hash.as_bytes().to_vec(), path.map(<[u8]>::to_vec)],
            |_| Ok(()),
        )
        .optional()?
        .is_some())
}

fn note_redacted_in(conn: &Connection, hash: &Hash, path: &[u8]) -> Result<()> {
    conn.execute(
        "INSERT OR IGNORE INTO redacted_nodes (hash, path) VALUES (?1, ?2)",
        params![hash.as_bytes().to_vec(), path.to_vec()],
    )?;
    Ok(())
}

/// Whether `hash` was served to this store as part of `origin`'s trie (§5.5).
fn owns_node_in(conn: &Connection, origin: &OriginId, hash: &Hash) -> Result<bool> {
    Ok(conn
        .query_row(
            "SELECT 1 FROM trie_node_origins WHERE origin_id = ?1 AND hash = ?2",
            params![origin.canonical(), hash.as_bytes().to_vec()],
            |_| Ok(()),
        )
        .optional()?
        .is_some())
}

fn note_owned_in(conn: &Connection, origin: &OriginId, hash: &Hash) -> Result<()> {
    conn.execute(
        "INSERT OR IGNORE INTO trie_node_origins (origin_id, hash) VALUES (?1, ?2)",
        params![origin.canonical(), hash.as_bytes().to_vec()],
    )?;
    Ok(())
}

/// Reads a 32-byte hash column.
///
/// The message carries the length found: it is what distinguishes a
/// truncated blob from a wrong-column read.
pub(crate) fn hash_column(bytes: Vec<u8>, column: &'static str) -> Result<Hash> {
    Hash::from_slice(&bytes)
        .map_err(|_| StoreError::column(column, format!("{} bytes, not 32", bytes.len())))
}

/// Reads a 32-byte device-key column.
pub(crate) fn key_column(bytes: Vec<u8>, column: &'static str) -> Result<NodeId> {
    let arr: [u8; 32] = bytes
        .try_into()
        .map_err(|_| StoreError::column(column, "not 32 bytes"))?;
    NodeId::from_bytes(&arr).map_err(|e| StoreError::column(column, e.to_string()))
}

/// Reads an origin-id column.
pub(crate) fn origin_column(text: String, column: &'static str) -> Result<OriginId> {
    OriginId::from_str(&text).map_err(|e| StoreError::column(column, e.to_string()))
}

